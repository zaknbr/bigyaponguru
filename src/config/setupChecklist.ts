/**
 * Returns filtered tasks based on the user's business profile & calculated plan
 */
export function getFilteredSetupTasks(profile: BusinessProfile, plan: CalculatedPlan): SetupTask[] {
  return ALL_SETUP_TASKS.filter((task) => {
    // If task is pixel, show only if user sells via website
    if (task.id === 'setup-pixel') {
      return profile.salesChannel === 'website';
    }

    // If task is tiktok, show if user has tiktok or plan recommends tiktok (>10% share)
    if (task.id === 'setup-tiktok-ads') {
      return profile.hasTiktok || plan.platformMix.tiktokShare > 10;
    }

    // Always include Facebook Page, Ads Manager, Payment, and Pre-launch checks
    return true;
  });
}
